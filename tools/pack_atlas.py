"""Packs game/assets/sprites/*.png into one atlas so Godot can batch draw calls.
    python tools/pack_atlas.py  ->  game/assets/atlas.png + game/assets/atlas.json
"""
import json, os, glob
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), "..", "game", "assets")
PAD = 2
files = sorted(glob.glob(os.path.join(ROOT, "sprites", "*.png")))
ims = [(os.path.splitext(os.path.basename(f))[0], Image.open(f).convert("RGBA")) for f in files]
ims.sort(key=lambda t: (-t[1].height, -t[1].width, t[0]))
W = 512
x = y = row_h = 0
rects = {}
for name, im in ims:
    w, h = im.width + PAD * 2, im.height + PAD * 2
    if x + w > W:
        x, y, row_h = 0, y + row_h, 0
    rects[name] = (x + PAD, y + PAD, im.width, im.height)
    x += w
    row_h = max(row_h, h)
H = 1
while H < y + row_h:
    H *= 2
atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
for name, im in ims:
    rx, ry, _, _ = rects[name]
    atlas.paste(im, (rx, ry))
atlas.save(os.path.join(ROOT, "atlas.png"))
# Regions as a GDScript constant (a .json file wouldn't be included in exports by default).
lines = ",\n".join(f'\t"{k}": [{v[0]}, {v[1]}, {v[2]}, {v[3]}]' for k, v in sorted(rects.items()))
gd = ("class_name AtlasRegions\nextends RefCounted\n## Generated by tools/pack_atlas.py. Don't edit by hand.\n\n"
      "const REGIONS := {\n" + lines + "\n}\n")
open(os.path.join(ROOT, "..", "scripts", "atlas_regions.gd"), "w").write(gd)
print(f"atlas {W}x{H}, {len(rects)} sprites")
